#!/usr/bin/env python3
"""Real Termux:GUI fixture. Used only by android_e2e.py with explicit --device.

This fixture writes a small atomic JSON state file for the test controller.
UI events are generated by adb shell input, not by directly calling callbacks.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import tempfile
import time

from termux_kivy import (
    App, BoxLayout, Button, CheckBox, Label, TextInput,
)


class DeviceFixture(App):
    def __init__(self, trace):
        super().__init__()
        self.trace = Path(trace)
        self.clicks = 0
        self.checked = False
        self.typed = ""
        self.events = []
        self.ready = False

    def _write(self, kind, **payload):
        stamp = time.time()
        self.events.append({"timestamp": stamp, "type": kind, **payload})
        state = {
            "ready": self.ready,
            "pid": os.getpid(),
            "clicks": self.clicks,
            "checked": self.checked,
            "typed": self.typed,
            "events": self.events,
        }
        self.trace.parent.mkdir(parents=True, exist_ok=True)
        fd, tempname = tempfile.mkstemp(
            prefix=".e2e-", suffix=".json.tmp", dir=str(self.trace.parent)
        )
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as output:
                json.dump(state, output, ensure_ascii=False, indent=2)
                output.flush()
                os.fsync(output.fileno())
            os.replace(tempname, self.trace)
        finally:
            if os.path.exists(tempname):
                os.unlink(tempname)
        print(f"[DEVICE FIXTURE] {kind} data={payload!r} state={state!r}", flush=True)

    def build(self):
        content = BoxLayout(orientation="vertical")
        content.add_widget(Label(text="TK-E2E-READY"))
        self.status = content.add_widget(Label(text="TK-E2E-COUNT:0"))
        self.button = content.add_widget(Button(text="TK-E2E-TAP"))
        self.button.bind(on_press=self.clicked)
        self.entry = content.add_widget(TextInput(text=""))
        self.entry.bind(text=self.text_changed)
        self.checkbox = content.add_widget(CheckBox(text="TK-E2E-CHECK"))
        self.checkbox.bind(active=self.checkbox_changed)
        return content

    def clicked(self, _sender):
        self.clicks += 1
        self.status.text = f"TK-E2E-COUNT:{self.clicks}"
        self._write("click", count=self.clicks)

    def text_changed(self, _sender, text):
        self.typed = text
        self._write("text", value=text)

    def checkbox_changed(self, _sender, active):
        self.checked = active
        self._write("check", checked=active)

    def on_start(self):
        self.ready = True
        self._write("ready")

    def on_stop(self):
        self.ready = False
        self._write("stop")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--trace", required=True, type=Path)
    args = parser.parse_args()
    DeviceFixture(args.trace).run()
